export function getDestinationCoords(name?: string | null): [number, number] {
  if (!name) return [16.8524, 74.5815]; // Default to Sangli hub
  const trimmed = name.trim();
  if (ALL_DESTINATION_COORDS[trimmed]) {
    return ALL_DESTINATION_COORDS[trimmed];
  }
  // Case-insensitive match
  const lower = trimmed.toLowerCase();
  for (const [key, coords] of Object.entries(ALL_DESTINATION_COORDS)) {
    if (key.toLowerCase() === lower || lower.includes(key.toLowerCase()) || key.toLowerCase().includes(lower)) {
      return coords;
    }
  }
  return [20.5937, 78.9629]; // Geographic center of India fallback
}
